#!/usr/bin/env python3
"""Regenerate docs/performance.md from a benchmark_results_*.json file.

Usage: generate_performance_doc.py <results.json> [output_path]

Keeps the hand-written prose (intro paragraphs, methodology explanation,
"Optimizing Array Workloads" code sample) as static text below, and
regenerates only the data-driven parts: the implementations table's version
numbers, the run date, the per-category summary and detailed-results
tables, and the methodology footer's date/platform/version line. This
mirrors the fix for CHANGELOG.md's staleness earlier in this project's
history - hand-written docs that only get updated "when someone remembers
to" reliably go stale; this one gets regenerated by every release's
benchmark job instead.

Two test shapes need different table layouts:
- Cross-language tests (js_ms is not None): jsonatapy / jsonatapy(json I/O) /
  jsonata-core(pure Rust) / jsonata-js / jsonata-python / jsonata-rs /
  speedup-vs-JS columns.
- jsonatapy-only "Path Comparison" tests (js_ms is None): these exercise
  jsonatapy's own evaluate() vs evaluate_with_data()/evaluate_json() paths,
  not a cross-implementation comparison, so they get a simpler
  Operation/jsonatapy-ms/Iterations table instead.
"""

import json
import sys
from pathlib import Path

CATEGORY_ORDER = [
    "Simple Paths",
    "Array Operations",
    "Complex Transformations",
    "Deep Nesting",
    "String Operations",
    "Higher-Order Functions",
    "Realistic Workload",
    "Path Comparison",
]

INTRO = """# Performance Benchmarks

jsonatapy is a high-performance Rust implementation of JSONata with Python bindings. This page presents benchmark comparisons against other JSONata implementations.

**These numbers come from a dedicated, self-hosted Mac Mini (Apple Silicon), not a shared cloud CI runner** — single-tenant physical hardware with no other workloads competing for CPU. This matters: single-sample measurements on a shared/virtualized runner were previously noisy enough that identical code, measured twice, swung -66% to +120%. Every number below is also the *minimum* of {repeat_trials} independent measurement trials per test (not an average) — for CPU-bound microbenchmarks, interference can only make a run slower than the code's true achievable speed, never faster, so the minimum across repeated trials is the best available estimate of that true speed.

## Implementations Tested

| Implementation | Language | Version | Description |
|----------------|----------|---------|-------------|
| **jsonatapy** | Rust + Python | {jsonatapy_version} | This project (compiled Rust extension via PyO3); data crosses the boundary as Python dicts |
| **jsonatapy** (JSON string I/O) | Rust + Python | {jsonatapy_version} | Same library via `evaluate_json`: data crosses as JSON strings, parsed/serialized by serde per call |
| **jsonata-core** (pure Rust) | Rust | {jsonatapy_version} | This project's engine measured as a Rust library — no Python at all, data pre-parsed, expression pre-compiled (criterion methodology, per table row) |
| **jsonata-js** | JavaScript | 2.1.0 | Reference implementation (Node.js {node_version}) |
| **jsonata-python** | Python | unknown | Python wrapper embedding a JS engine (Duktape) |
| **jsonata-rs** | Rust | 0.3 | Third-party Rust implementation (Stedi's crate — not this project; CLI harness, no Python overhead) |

### Methodology: compile-once, evaluate-many

Every implementation below is measured the way a real caller who evaluates the same expression repeatedly would use it, not its slowest possible one-off call:

- **jsonatapy** — `jsonatapy.compile(expr)` once, then `.evaluate(data)` in the timed loop. No further reuse is available; the compiled bytecode is already cached on the expression object.
- **jsonata-core (pure Rust)** — `Expression::compile(expr)` once, input parsed to a `JValue` once, then `Expression::evaluate(&data)` in an in-process timed loop with warmup — the same methodology as the criterion suite (`benches/`), reported per table row. The gap between this column and the jsonatapy columns *is* the Python boundary cost; the engine is identical.
- **jsonata-js** — `jsonata(expr)` once, then `.evaluate(data)` in the timed loop. Same story: this is already the library's fastest repeated-call path.

- **jsonata-python** — uses its documented `Context` object (`ctx = jsonata.Context()`, then `ctx(expr, data)` in the loop) rather than the one-off `transform()` convenience function. `transform()` re-bootstraps an embedded Duktape engine — reloading the `jsonata.js` library into it — on every single call; reusing a `Context` keeps that engine warm and is the library's own documented path for repeated evaluation. It is *not* a true compile-once equivalent, since `Context.__call__` still re-parses the expression string on every call, so some of the remaining gap to jsonatapy/jsonata-js is real parsing cost this library doesn't let a caller amortize away.


Benchmarks run on {run_date}."""

OPTIMIZING_TIPS = """## Performance Characteristics

**Faster than JavaScript:**

{faster_categories}

**Comparable to JavaScript:**

{comparable_categories}

### Optimizing Array Workloads

For array-heavy workloads, the dominant cost is converting Python dicts to Rust values on every call. Use `JsonataData` to pre-convert data once and reuse across multiple evaluations:

```python
import jsonatapy

data = {{...}}  # your data
expr = jsonatapy.compile("products[price > 100]")

# Pre-convert once
jdata = jsonatapy.JsonataData(data)

# Reuse many times (3-15x faster than evaluate(dict))
result = expr.evaluate_with_data(jdata)
```

## Methodology

- **Date:** {run_date}
- **Platform:** {platform}
- **Python:** {python_version}
- **Node.js:** {node_version}
- All times are total wall-clock time for the stated number of iterations
- Each benchmark includes a warmup phase before measurement
- 'vs JS' column shows jsonatapy speedup relative to the JavaScript reference implementation
- Values > 1x mean jsonatapy is faster; < 1x means JavaScript is faster
"""


def speedup_label(speedup: float) -> str:
    if speedup >= 1.0:
        return f"**{speedup:.1f}x faster**"
    return f"{1 / speedup:.1f}x slower"


def category_summary_table(results: list[dict]) -> str:
    lines = ["| Category | jsonatapy vs JS |", "|----------|----------------|"]
    for category in CATEGORY_ORDER:
        if category in SIMPLE_TABLE_CATEGORIES:
            continue
        rows = [r for r in results if r["category"] == category and r.get("js_ms")]
        if not rows:
            continue
        avg_speedup = sum(r["jsonatapy_speedup"] for r in rows) / len(rows)
        lines.append(f"| {category} | {speedup_label(avg_speedup)} |")
    return "\n".join(lines)


# "Path Comparison" tests exercise jsonatapy's OWN evaluate() vs
# evaluate_with_data()/evaluate_json() paths, not a cross-implementation
# comparison - some rows carry a js_ms value anyway (inherited from a
# related "Realistic Workload" test with the same underlying expression),
# but that's not this category's point, so it always gets the simpler
# Operation/jsonatapy-ms/Iterations table regardless of what fields happen
# to be populated.
SIMPLE_TABLE_CATEGORIES = {"Path Comparison"}


def fmt_ms(value: float | None) -> str:
    return f"{value:.3f}" if value is not None else "N/A"


def detailed_table(category: str, results: list[dict]) -> str:
    rows = [r for r in results if r["category"] == category]
    if not rows:
        return ""

    out = [f"### {category}", ""]

    if category in SIMPLE_TABLE_CATEGORIES:
        out.append("| Operation | jsonatapy (ms) | Iterations |")
        out.append("|-----------|---------------|------------|")
        for r in rows:
            out.append(f"| {r['name']} | {fmt_ms(r['jsonatapy_ms'])} | {r['iterations']} |")
        out.append("")
    else:
        out.append(
            "| Operation | Data Size | jsonatapy | jsonatapy (json I/O) | jsonata-core (pure Rust) | jsonata-js | jsonata-python | jsonata-rs | vs JS |"
        )
        out.append(
            "|-----------|-----------|-----------|----------------------|--------------------------|------------|----------------|------------|-------|"
        )
        for r in rows:
            vs_js = (
                speedup_label(r["jsonatapy_speedup"])
                if r.get("js_ms") and r.get("jsonatapy_speedup")
                else "N/A"
            )
            out.append(
                f"| {r['name']} | {r['data_size']} | {fmt_ms(r['jsonatapy_ms'])} | "
                f"{fmt_ms(r['jsonatapy_json_ms'])} | {fmt_ms(r.get('jsonata_core_ms'))} | "
                f"{fmt_ms(r.get('js_ms'))} | {fmt_ms(r.get('jsonata_python_ms'))} | "
                f"{fmt_ms(r.get('jsonata_rs_ms'))} | {vs_js} |"
            )
        out.append("")

    return "\n".join(out)


def main() -> int:
    if len(sys.argv) < 2:
        print("Usage: generate_performance_doc.py <results.json> [output_path]", file=sys.stderr)
        return 2

    results_path = Path(sys.argv[1])
    output_path = (
        Path(sys.argv[2])
        if len(sys.argv) > 2
        else Path(__file__).parent.parent.parent / "docs" / "performance.md"
    )

    with open(results_path) as f:
        data = json.load(f)

    results = data["results"]
    platform = data.get("platform", "unknown")
    python_version = data.get("python_version", "unknown")
    run_date = data.get("timestamp", "unknown")[:10]
    repeat_trials = data.get("repeat_trials", "an unknown number of")

    try:
        import jsonatapy

        jsonatapy_version = jsonatapy.__version__
    except ImportError:
        jsonatapy_version = "unknown"

    # benchmark_results_*.json doesn't record the Node version used, so ask
    # the `node` binary directly - only meaningful if this script runs in
    # the same environment the benchmark suite just ran in (true for its
    # intended use: a step in release.yml's benchmark job, right after
    # "Run benchmark suite").
    try:
        import subprocess

        node_version = subprocess.run(
            ["node", "--version"], capture_output=True, text=True, timeout=5
        ).stdout.strip()
        if not node_version:
            node_version = "unknown"
    except (OSError, subprocess.SubprocessError):
        node_version = "unknown"

    intro = INTRO.format(
        jsonatapy_version=jsonatapy_version,
        node_version=node_version,
        run_date=run_date,
        repeat_trials=repeat_trials,
    )

    summary = "## Summary by Category\n\n" + category_summary_table(results)

    detailed_sections = ["## Detailed Results", ""]
    for category in CATEGORY_ORDER:
        section = detailed_table(category, results)
        if section:
            detailed_sections.append(section)
    detailed = "\n".join(detailed_sections)

    faster, comparable = [], []
    for category in CATEGORY_ORDER:
        if category in SIMPLE_TABLE_CATEGORIES:
            continue
        rows = [r for r in results if r["category"] == category and r.get("js_ms")]
        if not rows:
            continue
        avg_speedup = sum(r["jsonatapy_speedup"] for r in rows) / len(rows)
        line = f"- {category} ({speedup_label(avg_speedup)})"
        if avg_speedup >= 1.0:
            faster.append(line)
        else:
            comparable.append(f"- {category}")

    footer = OPTIMIZING_TIPS.format(
        faster_categories="\n".join(faster) if faster else "- (none this run)",
        comparable_categories="\n".join(comparable) if comparable else "- (none this run)",
        run_date=run_date,
        platform=platform,
        python_version=python_version,
        node_version=node_version,
    )

    output_path.write_text(intro + "\n\n" + summary + "\n\n" + detailed + "\n" + footer)
    print(f"Wrote {output_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
